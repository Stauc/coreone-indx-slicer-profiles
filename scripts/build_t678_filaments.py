#!/usr/bin/env python3
"""Mixed-nozzle INDX filaments for PrusaSlicer 2.x: Prusament PLA for T6 (0.4 std) and T7 (0.25); GeeeTech TriColor Silk for T8 (1.0 HF). --write to apply."""
import sys, os, re, datetime
sys.path.insert(0, os.path.expanduser('~/scripts'))
from lib2x import parse_user, resolve, RP
WRITE = '--write' in sys.argv
HDR = datetime.datetime.utcnow().strftime('# generated by PrusaSlicer 2.9.7 on %Y-%m-%d at %H:%M:%S UTC')
KW = 'printer_notes=~/.*INDX_MIXED_NOZZLES.*/'
C6 = KW + ' and ((nozzle_diameter[0]==0.4 and !nozzle_high_flow[0]) or (nozzle_diameter[5]==0.4 and !nozzle_high_flow[5]))'
C7 = KW + ' and ((nozzle_diameter[0]==0.25) or (nozzle_diameter[6]==0.25))'
C8 = KW + ' and ((nozzle_diameter[0]==1 and nozzle_high_flow[0]) or (nozzle_diameter[7]==1 and nozzle_high_flow[7]))'
def ini(od): return ('\r\n'.join([HDR] + [f'{k} = {od[k]}' for k in sorted(od)]) + '\r\n').encode('utf-8')
def q(s): return '"%s"' % s
out = {}

T, _ = parse_user(RP + 'filament/Prusament PLA @COREONEINDX HF0.4 - GECO.ini')
P = resolve('filament', 'Prusament PLA @COREONEINDX HF0.4')
def base():
    S = dict((k, P.get(k, v)) for k, v in T.items())
    S.update(inherits='Prusament PLA @COREONEINDX HF0.4', compatible_printers='', filament_settings_id='""')
    return S
S6 = base()
S6.update(compatible_printers_condition=C6, filament_max_volumetric_speed='15', min_fan_speed='85', slowdown_below_layer_time='10', overhang_fan_speed_3='0',
          filament_notes=q('Prusament PLA for the standard-flow 0.4 mm nozzle on T6 of the mixed-nozzle INDX printers. Prusa ships PLA only for the HF 0.4; values follow Prusa standard-flow PLA: 15 mm3/s max, fan 85-100, slowdown 10 s.'))
S7 = base()
S7.update(compatible_printers_condition=C7, filament_max_volumetric_speed='10', min_fan_speed='85', slowdown_below_layer_time='6', overhang_fan_speed_3='0',
          start_filament_gcode=q('M572 S0.1 ; Pressure advance'),
          filament_notes=q('Prusament PLA for the 0.25 mm nozzle on T7 of the mixed-nozzle INDX printers. Values follow Prusa 0.25 INDX PLA: 10 mm3/s max, pressure advance 0.1, fan 85-100, slowdown 6 s.'))
out['Prusament PLA @COREONEINDX Std0.4 - T6'] = S6
out['Prusament PLA @COREONEINDX 0.25 - T7'] = S7

N = 'GeeeTech PLA TriColor Silk Blue+Purple+Black'
Tri, _ = parse_user(RP + 'filament/%s @COREONEINDX HF0.4.ini' % N)
S8 = dict(Tri)
assert 'M572 S0.025' in S8['start_filament_gcode']
S8.update(compatible_printers_condition=C8, filament_minimal_purge_on_wipe_tower='18', filament_retract_restart_extra_toolchange='0.05',
          start_filament_gcode=S8['start_filament_gcode'].replace('M572 S0.025', 'M572 S0.009'),
          filament_notes=q('GeeeTech Silk PLA TriColor Blue+Purple+Black on the 1.0 mm high-flow nozzle on T8 of the mixed-nozzle INDX printers. Same temperatures and 12.5 mm3/s flow limit as the 0.4 HF profile; pressure advance lowered to 0.009 (estimate) and purge/restart values follow Prusa 0.8 HF PLA.'))
out['%s @COREONEINDX 1.0HF - T8' % N] = S8

def ev(cond, nd, hf):
    e = cond.replace(KW, 'True'); e = re.sub(r'nozzle_diameter\[(\d)\]', r'ND[\1]', e); e = re.sub(r'nozzle_high_flow\[(\d)\]', r'HF[\1]', e)
    e = e.replace('!', ' not ')
    return bool(eval(e, {'ND': nd, 'HF': hf}))
ND = [0.4]*6 + [0.25, 1.0]; HFv = [1,1,1,1,1,0,0,1]
want = {'T6': (C6, 5), 'T7': (C7, 6), 'T8': (C8, 7)}
for tag, (c, idx) in want.items():
    res = []
    for k in range(8):
        sw_nd, sw_hf = ND[:], HFv[:]; sw_nd[0], sw_nd[k] = sw_nd[k], sw_nd[0]; sw_hf[0], sw_hf[k] = sw_hf[k], sw_hf[0]
        res.append(ev(c, sw_nd, sw_hf))
    asis = ev(c, ND, HFv)
    assert asis and res[idx], (tag, asis, res)
    print(f'{tag}: matches as-is: {asis} | per-extruder (swap) matches on: {[f"T{i+1}" for i,v in enumerate(res) if v]}')
for n, S in out.items():
    assert set(S) == set(T) if n.startswith('Prusament') else set(S) == set(Tri), n
    p = RP + 'filament/' + n + '.ini'; assert not os.path.exists(p), p
    print(('WRITE ' if WRITE else 'would write '), n)
    if WRITE: open(p, 'wb').write(ini(S))
