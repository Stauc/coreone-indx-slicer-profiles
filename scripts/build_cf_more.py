#!/usr/bin/env python3
"""PrusaSlicer 2.x carbon-fiber filaments for the mixed-nozzle INDX printers: PP CF on T6 (std 0.4); PC CF, PA11 CF, PP CF on T8 (1.0 HF). --write to apply."""
import sys, os, re, datetime
sys.path.insert(0, os.path.expanduser('~/scripts'))
from lib2x import parse_user, resolve, RP
WRITE = '--write' in sys.argv
HDR = datetime.datetime.utcnow().strftime('# generated by PrusaSlicer 2.9.7 on %Y-%m-%d at %H:%M:%S UTC')
KW = 'printer_notes=~/.*INDX_MIXED_NOZZLES.*/'
C6 = KW + ' and ((nozzle_diameter[0]==0.4 and !nozzle_high_flow[0]) or (nozzle_diameter[5]==0.4 and !nozzle_high_flow[5]))'
C8 = KW + ' and ((nozzle_diameter[0]==1 and nozzle_high_flow[0]) or (nozzle_diameter[7]==1 and nozzle_high_flow[7]))'
def ini(od): return ('\r\n'.join([HDR] + [f'{k} = {od[k]}' for k in sorted(od)]) + '\r\n').encode('utf-8')
def q(s): return '"%s"' % s
def pa(v): return q('M572 S%s ; Pressure advance\\nM573 R' % v)
T, _ = parse_user(RP + 'filament/Prusament PLA @COREONEINDX HF0.4 - GECO.ini')
def from_vendor(name, cond):
    P = resolve('filament', name)
    S = dict((k, P.get(k, v)) for k, v in T.items())
    S.update(inherits=name, compatible_printers='', compatible_printers_condition=cond, filament_settings_id='""')
    return S, P
def t8_extras(S): S.update(filament_minimal_purge_on_wipe_tower='18', filament_retract_restart_extra_toolchange='0.05')
out = {}

# ---- T6: PP CF (no INDX preset): CORE One 0.4 values, INDX-style pressure advance
S, P = from_vendor('Prusament PP Carbon Fiber @COREONE', C6)
S['start_filament_gcode'] = pa('0.036')
S['filament_notes'] = q('Prusament PP Carbon Fiber for the standard 0.4 mm nozzle on T6 of the mixed-nozzle INDX printers. Prusa has no INDX preset for it: values of the CORE One PP CF preset (270 C, bed 85/95, 4 mm3/s, no fan, extrusion multiplier 1.09), pressure advance 0.036 for 0.4. Abrasive: needs a hardened nozzle on T6. Print on the PP sheet, not PEI.')
out['Prusament PP Carbon Fiber @COREONEINDX Std0.4 - T6'] = S

# ---- T8: PC Blend CF: Prusa INDX HF0.4 preset + CORE One 0.8 numbers for a larger nozzle
S, P = from_vendor('Prusament PC Blend Carbon Fiber @COREONEINDX HF0.4', C8)
C8P = resolve('filament', 'Prusament PC Blend Carbon Fiber @COREONE 0.8')
for k in ('temperature', 'first_layer_temperature', 'filament_max_volumetric_speed', 'bridge_fan_speed'): S[k] = C8P[k]
S['start_filament_gcode'] = pa('0.011'); t8_extras(S)
S['filament_notes'] = q('Prusament PC Blend Carbon Fiber for the 1.0 mm high-flow nozzle on T8 of the mixed-nozzle INDX printers. Prusa has no 1.0 profile: INDX HF0.4 preset with the numbers of the CORE One 0.8 preset (285 C, 18 mm3/s); pressure advance 0.011 (trend of Prusa 0.4/0.6/0.8 values). Untested. Abrasive: needs a hardened nozzle on T8.')
out['Prusament PC Blend Carbon Fiber @COREONEINDX 1.0HF - T8'] = S

# ---- T8: PA11 CF: from the T6 PA11 CF profile, CORE One 0.8 flow
S, _ = parse_user(RP + 'filament/Prusament PA11 Carbon Fiber @COREONEINDX Std0.4 - T6.ini')
S = dict(S); C8P = resolve('filament', 'Prusament PA11 Carbon Fiber @COREONE 0.8')
S.update(compatible_printers_condition=C8, filament_max_volumetric_speed=C8P['filament_max_volumetric_speed'], start_filament_gcode=pa('0.011'))
t8_extras(S)
S['filament_notes'] = q('Prusament PA11 Carbon Fiber for the 1.0 mm high-flow nozzle on T8 of the mixed-nozzle INDX printers. Prusa has no INDX or 1.0 preset: CORE One PA11 CF values (285/275 C, bed 115/90, fan 15-20%) with the CORE One 0.8 flow limit (10 mm3/s); pressure advance 0.011. Untested. Abrasive: needs a hardened nozzle on T8.')
out['Prusament PA11 Carbon Fiber @COREONEINDX 1.0HF - T8'] = S

# ---- T8: PP CF: CORE One 0.8 values
S, P = from_vendor('Prusament PP Carbon Fiber @COREONE 0.8', C8)
S['start_filament_gcode'] = pa('0.010'); t8_extras(S)
S['filament_notes'] = q('Prusament PP Carbon Fiber for the 1.0 mm high-flow nozzle on T8 of the mixed-nozzle INDX printers. Prusa has no INDX or 1.0 preset: CORE One 0.8 PP CF values (270 C, bed 85/95, 8 mm3/s, no fan, extrusion multiplier 1.09); pressure advance 0.010. Untested. Abrasive: needs a hardened nozzle on T8. Print on the PP sheet, not PEI.')
out['Prusament PP Carbon Fiber @COREONEINDX 1.0HF - T8'] = S

for n, S in out.items():
    assert set(S) == set(T), (n, set(S) ^ set(T))
    p = RP + 'filament/' + n + '.ini'; assert not os.path.exists(p), p
    print(('WRITE ' if WRITE else 'would write '), n)
    print('    ', {k: S[k] for k in ('temperature', 'first_layer_temperature', 'bed_temperature', 'first_layer_bed_temperature', 'filament_max_volumetric_speed', 'min_fan_speed', 'max_fan_speed', 'extrusion_multiplier', 'filament_abrasive', 'filament_density', 'filament_type') if k in S},
          '| PA:', S['start_filament_gcode'].replace('\\n', ' / ')[:42], '| chamber', S.get('chamber_temperature'), S.get('chamber_minimal_temperature'))
    if WRITE: open(p, 'wb').write(ini(S))
