#!/usr/bin/env python3
"""Rebuild the T6 and T8 PA11 CF filaments straight from Prusa's PA11 CF preset (CORE One; 0.8 for T8). --write to apply (old files archived first)."""
import sys, os, re, datetime, shutil
sys.path.insert(0, os.path.expanduser('~/scripts'))
from lib2x import parse_user, resolve, RP
WRITE = '--write' in sys.argv
HDR = datetime.datetime.utcnow().strftime('# generated by PrusaSlicer 2.9.7 on %Y-%m-%d at %H:%M:%S UTC')
KW = 'printer_notes=~/.*INDX_MIXED_NOZZLES.*/'
C6 = KW + ' and ((nozzle_diameter[0]==0.4 and !nozzle_high_flow[0]) or (nozzle_diameter[5]==0.4 and !nozzle_high_flow[5]))'
C8 = KW + ' and ((nozzle_diameter[0]==1 and nozzle_high_flow[0]) or (nozzle_diameter[7]==1 and nozzle_high_flow[7]))'
def ini(od): return ('\r\n'.join([HDR] + [f'{k} = {od[k]}' for k in sorted(od)]) + '\r\n').encode('utf-8')
def q(s): return '"%s"' % s
def pa(v): return q('M572 S%s ; Pressure advance\\nM573 R' % v)
T, _ = parse_user(RP + 'filament/Prusament PLA @COREONEINDX HF0.4 - GECO.ini')
Q = resolve('filament', 'Prusament PA11 @COREONEINDX HF0.4')          # INDX PA11: fallback only for keys the CF preset does not define
def build(vname, cond, pav, notes):
    P = resolve('filament', vname)
    S = dict((k, P[k] if k in P else Q.get(k, v)) for k, v in T.items())
    S.update(inherits='', compatible_printers='', compatible_printers_condition=cond, filament_settings_id='""', start_filament_gcode=pa(pav), filament_notes=q(notes))
    return S, [k for k in T if k not in P]
out = {
 'Prusament PA11 Carbon Fiber @COREONEINDX Std0.4 - T6': build('Prusament PA11 Carbon Fiber @COREONE', C6, '0.05',
   'Prusament PA11 Carbon Fiber for the standard 0.4 mm nozzle on T6 of the mixed-nozzle INDX printers. All values from Prusa\'s own PA11 CF preset (CORE One, 0.4): 285/275 C, bed 115/90, 6.5 mm3/s, fan 15-20%, pressure advance 0.05. Prusa has no INDX PA11 CF preset. Abrasive: needs a hardened nozzle on T6.'),
 'Prusament PA11 Carbon Fiber @COREONEINDX 1.0HF - T8': build('Prusament PA11 Carbon Fiber @COREONE 0.8', C8, '0.016',
   'Prusament PA11 Carbon Fiber for the 1.0 mm high-flow nozzle on T8 of the mixed-nozzle INDX printers. Prusa has no 1.0 or INDX PA11 CF preset: values of its CORE One 0.8 mm PA11 CF preset (285/275 C, bed 115/90, 10 mm3/s, fan 15-20%, pressure advance 0.016). Untested. Abrasive: needs a hardened nozzle on T8.'),
}
out['Prusament PA11 Carbon Fiber @COREONEINDX 1.0HF - T8'][0].update(filament_minimal_purge_on_wipe_tower='18', filament_retract_restart_extra_toolchange='0.05')   # INDX tool-change tuning kept on every T8 profile
bk = RP + '_archive_20261108_PA11CF_before/'
for n, (S, missing) in out.items():
    assert set(S) == set(T), (n, set(S) ^ set(T))
    p = RP + 'filament/' + n + '.ini'; assert os.path.exists(p), p
    old, _ = parse_user(p)
    print(('WRITE ' if WRITE else 'would write '), n, '| keys filled from INDX PA11/template (not in Prusa CF preset):', len(missing))
    for k in sorted(set(S) | set(old)):
        if S.get(k) != old.get(k) and k != 'filament_notes': print('     %-42s %s  =>  %s' % (k, str(old.get(k))[:46], str(S.get(k))[:46]))
    if WRITE:
        os.makedirs(bk, exist_ok=True); shutil.copy2(p, bk + n + '.ini'); open(p, 'wb').write(ini(S))
