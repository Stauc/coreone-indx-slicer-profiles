full = NAME + ' @Prusa CORE One INDX'
d = {'compatible_printers': COMPAT, 'default_filament_colour': ['#E0E0E0'], 'enable_pressure_advance': ['1'], 'pressure_advance': [PA],
     'fan_cooling_layer_time': ['25'], 'fan_max_speed': ['65'], 'fan_min_speed': ['30'], 'filament_cost': ['10.49'], 'filament_density': ['1.27'],
     'filament_flow_ratio': ['0.98'], 'filament_max_volumetric_speed': ['18'], 'filament_notes': [NOTE], 'filament_settings_id': [full],
     'filament_vendor': ['GeeeTech'], 'from': 'User', 'hot_plate_temp': ['90'], 'hot_plate_temp_initial_layer': ['85'],
     'textured_plate_temp': ['90'], 'textured_plate_temp_initial_layer': ['85'], 'inherits': 'Prusament PETG @Prusa CORE One INDX',
     'is_custom_defined': '0', 'name': full, 'nozzle_temperature': ['245'], 'nozzle_temperature_initial_layer': ['250'],
     'nozzle_temperature_range_low': ['220'], 'nozzle_temperature_range_high': ['250'], 'overhang_fan_speed': ['60'], 'slow_down_layer_time': ['9'], 'version': '2.3.1.0'}
out[ORCA + full + '.json'] = jb(d)
out[ORCA + full + '.info'] = f'sync_info = create\r\nuser_id = \r\nsetting_id = \r\nbase_id = GFSA04\r\nupdated_time = {int(time.time())}\r\n'.encode()
WM = json.load(open(ORCA + 'GeeeTech PETG White @MINIIS.json', encoding='utf-8'))
