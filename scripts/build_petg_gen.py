out = collections.OrderedDict()
def ini_bytes(S):
    return ('\r\n'.join([HDR] + [f'{k} = {S[k]}' for k in sorted(S)]) + '\r\n').encode('utf-8')
# PS 2.x INDX
T, _ = parse_user(RP + 'filament/Prusament PETG @COREONEINDX HF0.4 - GeeeTech.ini')
P = resolve('filament', 'Prusament PETG @COREONEINDX HF0.4')
S = dict((k, P.get(k, v)) for k, v in T.items())
