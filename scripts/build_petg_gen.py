S['start_filament_gcode'] = g.replace('M572 S0.058', 'M572 S' + PA)
assert set(S) == set(T)
out[RP + 'filament/' + NAME + ' @COREONEINDX HF0.4.ini'] = ini_bytes(S)
print('INDX changes vs Prusament parent:', {k: (P[k][:14], S[k][:14]) for k in S if k in P and P[k] != S[k] and k not in ('filament_notes', 'compatible_printers_condition', 'inherits')})
# PS 2.x Mini IS (the White tune, neutral colour)
TM, _ = parse_user(RP + 'filament/GeeeTech PETG White @MINIIS.ini')
SM = dict(TM); SM.update(filament_colour='#E0E0E0', filament_vendor='GeeeTech', filament_cost='10.49', filament_density='1.27',
                         filament_notes='"' + NOTE + ' Mini IS: same values as the GeeeTech PETG White @MINIIS tune (245 C, 24 mm3/s, retract 0.8)."')
out[RP + 'filament/' + NAME + ' @MINIIS.ini'] = ini_bytes(SM)
print('Mini changes vs White:', {k: (TM[k][:14], SM[k][:14]) for k in SM if TM.get(k) != SM[k] and k != 'filament_notes'})
# PS3
PARENT = 'Pg/x3f1fSQGhLv63C+xlpw'
COND3 = '((printer.base_model == "COREONE_INDX") and (tool.nozzle_diameter == 0.4) and tool.nozzle_high_flow)'
rid = lambda: base64.b64encode(secrets.token_bytes(16)).decode().rstrip('=')
vals = collections.OrderedDict((k, ("'%s'" % v if k == 'filament_colour' else v)) for k, v in OV.items())
vals['pressure_advance_value'] = PA; vals['filament_notes'] = "'" + NOTE.replace("'", "''") + "'"
body = ''.join(f'    {k}: {v}\n' for k, v in vals.items())
txt = f'''kind: filament
id: {uuid.uuid4()}
variants:
- condition: {COND3}
  id: {rid()}
  name: {NAME} @COREONEINDX HF0.4
  unconditional_inherits:
  - {PARENT}
  values:
{body}  features:
    based_id: {PARENT}
    based_root_id: Prusament PETG
'''
v = yaml.safe_load(txt)['variants'][0]; assert v['values']['temperature'] == 245 and v['unconditional_inherits'] == [v['features']['based_id']]
out[PS3 + 'filament-' + NAME + ' @COREONEINDX HF0.4.yaml'] = txt.encode()
# Orca
COMPAT = json.load(open(ORCA + 'Prusament PETG @Prusa CORE One INDX - ICE Rob.json', encoding='utf-8'))['compatible_printers']
