def rid(): return base64.b64encode(secrets.token_bytes(16)).decode().rstrip('=')
def ps3(name, ov, note, pa=None):
    vals = collections.OrderedDict()
    for k, v in ov.items():
        vals[k] = "'%s'" % v if k == 'filament_colour' else v
    if pa: vals['pressure_advance_value'] = pa
    vals['filament_notes'] = "'" + note.replace("'", "''") + "'"
    body = ''.join(f'    {k}: {v}\n' for k, v in vals.items())
    txt = f'''kind: filament
id: {uuid.uuid4()}
variants:
- condition: {COND3}
  id: {rid()}
  name: {name} @COREONEINDX HF0.4
  unconditional_inherits:
  - {PARENT}
  values:
{body}  features:
    based_id: {PARENT}
    based_root_id: Prusament PETG
'''
    d = yaml.safe_load(txt)
    v = d['variants'][0]
    assert d['kind'] == 'filament' and v['unconditional_inherits'] == [v['features']['based_id']]
    assert v['values']['temperature'] == int(ov['temperature']) and str(v['values']['filament_colour']).startswith('#')
    out[PS3 + 'filament-' + name + ' @COREONEINDX HF0.4.yaml'] = txt.encode('utf-8')
