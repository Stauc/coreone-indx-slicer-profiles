NOW = datetime.datetime.utcnow().strftime('# generated by PrusaSlicer 2.9.6 on %Y-%m-%d at %H:%M:%S UTC')

def write_ini(path, od, header=None):
    lines = [header or NOW]
    for k in sorted(od): lines.append(f'{k} = {od[k]}')
    open(path, 'wb').write(('\r\n'.join(lines) + '\r\n').encode('utf-8'))

