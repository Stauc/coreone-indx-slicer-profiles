COND_HF04 = 'printer_model=~/(COREONE_INDX8T|COREONE_INDX4T)/ and nozzle_diameter[0]==0.4 and nozzle_high_flow[0]'
def cond(tool, dia, hf):
    return f'printer_notes=~/.*{KEYWORD}.*/ and nozzle_diameter[{tool-1}]=={dia}' + (f' and nozzle_high_flow[{tool-1}]' if hf else f' and !nozzle_high_flow[{tool-1}]')
FEATURE_EXT = ['perimeter_extruder', 'infill_extruder', 'solid_infill_extruder', 'support_material_extruder', 'support_material_interface_extruder']

TEMPLATE, _ = parse_user(RP + 'print/0.15mm Detail @COREONEINDX HF0.4 - Color.ini')   # full 198-key set (non-vendor keys are PS defaults)
def from_vendor(parent):
    S = collections.OrderedDict((k, v) for k, v in TEMPLATE.items())
    for k, v in resolve('print', parent).items():
        if k in TEMPLATE: S[k] = v
        else: print('   (dropping vendor key not in PS 2.9.6 print config:', repr(k), 'from', parent + ')')
    for k in ('support_material_auto', 'extra_perimeters', 'support_tree_branch_diameter_double_wall'):   # undo the user's own tweaks in the template file
        S[k] = resolve('print', parent).get(k, {'support_material_auto': '0', 'extra_perimeters': '0', 'support_tree_branch_diameter_double_wall': '8'}[k])
    S['inherits'] = parent
    S['print_settings_id'] = ''; S['compatible_printers'] = ''
    return S
def set_ext(S, n):
    for k in FEATURE_EXT: S[k] = str(n)

