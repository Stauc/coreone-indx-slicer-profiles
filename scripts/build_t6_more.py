#!/usr/bin/env python3
"""T6 (standard 0.4) filaments for the mixed-nozzle INDX printers, PrusaSlicer 2.x: white PLA, white PETG, PC Blend CF, PA11 CF. --write to apply."""
import sys, os, re, datetime
sys.path.insert(0, os.path.expanduser('~/scripts'))
from lib2x import parse_user, resolve, RP
WRITE = '--write' in sys.argv
HDR = datetime.datetime.utcnow().strftime('# generated by PrusaSlicer 2.9.7 on %Y-%m-%d at %H:%M:%S UTC')
KW = 'printer_notes=~/.*INDX_MIXED_NOZZLES.*/'
C6 = KW + ' and ((nozzle_diameter[0]==0.4 and !nozzle_high_flow[0]) or (nozzle_diameter[5]==0.4 and !nozzle_high_flow[5]))'
def ini(od): return ('\r\n'.join([HDR] + [f'{k} = {od[k]}' for k in sorted(od)]) + '\r\n').encode('utf-8')
def q(s): return '"%s"' % s
T, _ = parse_user(RP + 'filament/Prusament PLA @COREONEINDX HF0.4 - GECO.ini')            # 87-key template
def from_vendor(name):
    P = resolve('filament', name)
    S = dict((k, P.get(k, v)) for k, v in T.items())
    S.update(inherits=name, compatible_printers='', compatible_printers_condition=C6, filament_settings_id='""')
    return S, P
out = {}

# ---- white PLA: Prusament PLA INDX base + the user's own Sunlu White tune (205/210, 12 mm3/s, fan 100)
S, P = from_vendor('Prusament PLA @COREONEINDX HF0.4')
W, _ = parse_user(RP + 'filament/Sunlu PLA White - Gee new.ini')
Sl, _ = parse_user(RP + 'filament/Sunlu PLA @COREONEINDX HF0.4 - 220-210 - FLATTENED.ini')
S.update(temperature=W['temperature'], first_layer_temperature=W['first_layer_temperature'], bed_temperature=W['bed_temperature'], first_layer_bed_temperature=W['first_layer_bed_temperature'],
         filament_max_volumetric_speed=W['filament_max_volumetric_speed'], min_fan_speed=W['min_fan_speed'], max_fan_speed=W['max_fan_speed'], bridge_fan_speed=W['bridge_fan_speed'],
         slowdown_below_layer_time=W['slowdown_below_layer_time'], overhang_fan_speed_3='0',
         filament_density=W['filament_density'], filament_colour='#FFFFFF', filament_vendor='Sunlu', filament_cost=Sl['filament_cost'], filament_spool_weight=Sl['filament_spool_weight'],
         filament_notes=q('Sunlu PLA White for the standard 0.4 mm nozzle on T6 of the mixed-nozzle INDX printers. Temperatures, flow limit and fan taken from your Sunlu PLA White tune (205/210 C, 12 mm3/s, fan 100%) to keep white from clogging.'))
out['Sunlu PLA White @COREONEINDX Std0.4 - T6'] = S

# ---- white PETG: the user's own INDX GeeeTech PETG tune
G, _ = parse_user(RP + 'filament/Prusament PETG @COREONEINDX HF0.4 - GeeeTech.ini')
S = dict(G)
S.update(compatible_printers_condition=C6, filament_colour='#FFFFFF', filament_vendor='GeeeTech',
         filament_notes=q('GeeeTech PETG White for the standard 0.4 mm nozzle on T6 of the mixed-nozzle INDX printers. Copy of your GeeeTech PETG INDX tune (250/255 C, bed 90/85, 0.98 flow, 10 mm3/s).'))
out['GeeeTech PETG White @COREONEINDX Std0.4 - T6'] = S

# ---- PC Blend Carbon Fiber: Prusa INDX HF0.4 preset with the standard-flow numbers of Prusa's CORE One preset
S, P = from_vendor('Prusament PC Blend Carbon Fiber @COREONEINDX HF0.4')
C1 = resolve('filament', 'Prusament PC Blend Carbon Fiber @COREONE')
for k in ('temperature', 'first_layer_temperature', 'filament_max_volumetric_speed', 'bridge_fan_speed'): S[k] = C1[k]
S['filament_notes'] = q('Prusament PC Blend Carbon Fiber for the standard 0.4 mm nozzle on T6 of the mixed-nozzle INDX printers. Prusa INDX HF0.4 preset with the standard-nozzle values of the CORE One preset: 285 C, 9 mm3/s, bridge fan 25%. Abrasive: needs a hardened nozzle on T6.')
out['Prusament PC Blend Carbon Fiber @COREONEINDX Std0.4 - T6'] = S

# ---- PA11 Carbon Fiber: no INDX preset exists; Prusa INDX PA11 preset + the carbon-fiber properties of the CORE One PA11 CF preset
S, P = from_vendor('Prusament PA11 @COREONEINDX HF0.4')
C1 = resolve('filament', 'Prusament PA11 Carbon Fiber @COREONE')
for k in ('temperature', 'first_layer_temperature', 'bed_temperature', 'first_layer_bed_temperature', 'filament_max_volumetric_speed', 'min_fan_speed', 'max_fan_speed', 'bridge_fan_speed',
          'slowdown_below_layer_time', 'fan_below_layer_time', 'disable_fan_first_layers', 'cooling_slowdown_logic', 'extrusion_multiplier', 'filament_abrasive', 'filament_density', 'filament_cost',
          'filament_colour', 'filament_shrinkage_compensation_xy', 'filament_shrinkage_compensation_z', 'filament_infill_max_crossing_speed', 'filament_infill_max_speed',
          'chamber_temperature', 'chamber_minimal_temperature', 'filament_type'):
    if k in C1 and k in S: S[k] = C1[k]
S['inherits'] = ''
S['filament_notes'] = q('Prusament PA11 Carbon Fiber for the standard 0.4 mm nozzle on T6 of the mixed-nozzle INDX printers. Prusa has no INDX preset for it: Prusa INDX PA11 preset (pressure advance, purge) with the carbon-fiber values of the CORE One PA11 CF preset (285/275 C, 6.5 mm3/s, fan 15-20%). Abrasive: needs a hardened nozzle on T6.')
out['Prusament PA11 Carbon Fiber @COREONEINDX Std0.4 - T6'] = S

for n, S in out.items():
    assert set(S) == set(T), (n, set(S) ^ set(T))
    p = RP + 'filament/' + n + '.ini'; assert not os.path.exists(p), p
    print(('WRITE ' if WRITE else 'would write '), n)
    print('    ', {k: S[k] for k in ('temperature', 'first_layer_temperature', 'bed_temperature', 'first_layer_bed_temperature', 'filament_max_volumetric_speed', 'min_fan_speed', 'max_fan_speed', 'filament_abrasive', 'filament_colour', 'filament_density') if k in S},
          '| PA:', S['start_filament_gcode'].replace('\\n', ' / ')[:42], '| chamber', S.get('chamber_temperature'), S.get('chamber_minimal_temperature'))
    if WRITE: open(p, 'wb').write(ini(S))
