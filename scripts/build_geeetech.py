#!/usr/bin/env python3
"""GeeeTech PLA Matte Grey: INDX + Mini IS for PrusaSlicer 2.x / PS3 alpha13 (INDX only) / OrcaSlicer. --write to apply."""
import sys, os, json, time, glob, mmap, datetime, collections, uuid, base64, secrets
sys.path.insert(0, os.path.expanduser('~/scripts'))
from lib2x import parse_user, resolve, RP
WRITE = '--write' in sys.argv
H = os.path.expanduser('~/mnt/')
NOW_HDR = datetime.datetime.utcnow().strftime('# generated by PrusaSlicer 2.9.6 on %Y-%m-%d at %H:%M:%S UTC')
EPOCH = int(time.time())

# ---------------- researched / chosen values ----------------
COLOUR = '#A4A4A4'                 # no hex published for Matte Grey; same grey as the existing Stone Gray profile
COST = '36.29'                     # what the existing GeeeTech PLA profile uses
SPOOL = '193'                      # same as the other GeeeTech profiles (community DB says 114 g, Geeetech publishes none)
NOTES = ('GeeeTech Matte PLA Grey 1.75 mm, 1 kg. Geeetech product page: nozzle 190-220 C, heated bed 50-70 C, +/-0.03 mm. '
         'Community database (Stone Grey): density 1.24, max flow 20 mm3/s, flow ratio 0.98, dry 45 C for 4 h.')
INDX = dict(temperature='210', first_layer_temperature='215', bed_temperature='55', first_layer_bed_temperature='55',
            filament_max_volumetric_speed='20', extrusion_multiplier='0.98')

out = collections.OrderedDict()   # path -> bytes

# ================= PrusaSlicer 2.x =================
def ini(od, header=NOW_HDR):
    return ('\r\n'.join([header] + [f'{k} = {od[k]}' for k in sorted(od)]) + '\r\n').encode('utf-8')

T, _ = parse_user(RP + 'filament/Prusament PLA @COREONEINDX HF0.4 - GECO.ini')          # full 87-key dump
P = resolve('filament', 'Prusament PLA @COREONEINDX HF0.4')
S = collections.OrderedDict((k, P.get(k, v)) for k, v in T.items())
S['inherits'] = 'Prusament PLA @COREONEINDX HF0.4'
S['compatible_printers'] = ''
S.update(INDX)
S.update(filament_cost=COST, filament_density='1.24', filament_spool_weight=SPOOL, filament_vendor='GeeeTech',
         filament_colour=COLOUR, filament_notes='"%s"' % NOTES, filament_settings_id='""')
assert set(S) == set(T)
out[RP + 'filament/GeeeTech PLA Matte Grey @COREONEINDX HF0.4.ini'] = ini(S)

M, _ = parse_user(RP + 'filament/GeeeTech PLA Matte Stone Gray @MINIIS.ini')            # the user's calibrated Mini IS tune
M2 = collections.OrderedDict(M)
M2.update(filament_colour=COLOUR, filament_vendor='GeeeTech', filament_notes='"%s"' % NOTES)
assert set(M2) == set(M)
out[RP + 'filament/GeeeTech PLA Matte Grey @MINIIS.ini'] = ini(M2)

# ================= PrusaSlicer 3 alpha13 (INDX only) =================
def rid(): return base64.b64encode(secrets.token_bytes(16)).decode().rstrip('=')
ps3 = f'''kind: filament
id: {uuid.uuid4()}
variants:
- condition: ((printer.base_model == "COREONE_INDX") and (tool.nozzle_diameter == 0.4) and tool.nozzle_high_flow)
  id: {rid()}
  name: GeeeTech PLA Matte Grey @COREONEINDX HF0.4
  unconditional_inherits:
  - h2BZOYfPRV2UKu1BEaGnPw
  values:
    temperature: 210
    first_layer_temperature: 215
    extrusion_multiplier: 0.98
    filament_max_volumetric_speed: 20
    filament_cost: {COST}
    filament_density: 1.24
    filament_colour: '{COLOUR}'
    filament_vendor: GeeeTech
    filament_spool_weight: {SPOOL}
    filament_notes: '{NOTES}'
  features:
    based_id: h2BZOYfPRV2UKu1BEaGnPw
    based_root_id: Prusament PLA
'''
out[H + 'PrusaSlicer3-dev/presets/user/prusa-research-fff/PrusaResearch/filament-GeeeTech PLA Matte Grey @COREONEINDX HF0.4.yaml'] = ps3.encode('utf-8')
import yaml; yaml.safe_load(ps3)

# ================= OrcaSlicer =================
UD = H + 'Roaming--OrcaSlicer/user/default/filament/'
def dump(d): return (json.dumps(d, indent=4, ensure_ascii=False, sort_keys=True).replace('\n', '\r\n') + '\r\n').encode('utf-8')
def info(base): return ('sync_info = create\r\nuser_id = \r\nsetting_id = \r\nbase_id = %s\r\nupdated_time = %d\r\n' % (base, EPOCH)).encode()
# key existence check against the installed app
dll = open(H + 'Program Files--OrcaSlicer/OrcaSlicer.dll', 'rb'); mm = mmap.mmap(dll.fileno(), 0, access=mmap.ACCESS_READ)
NEWM = ['Prusa CORE One INDX 8T Mixed Nozzles - LAN', 'Prusa CORE One INDX 8T Mixed Nozzles - Connect']
SYSM = 'Prusa CORE One INDX 8T HF 0.4 nozzle'
nm = 'GeeeTech PLA Matte Grey @Prusa CORE One INDX'
oi = {'compatible_printers': [SYSM, SYSM + ' - LAN', SYSM + ' - Connect'] + NEWM,
      'default_filament_colour': [COLOUR], 'filament_cost': [COST], 'filament_density': ['1.24'], 'filament_flow_ratio': ['0.98'],
      'filament_max_volumetric_speed': ['20'], 'filament_notes': [NOTES], 'filament_settings_id': [nm], 'filament_vendor': ['GeeeTech'],
      'from': 'User', 'inherits': 'Prusament PLA @Prusa CORE One INDX', 'is_custom_defined': '0', 'name': nm,
      'nozzle_temperature': ['210'], 'nozzle_temperature_initial_layer': ['215'], 'nozzle_temperature_range_low': ['190'], 'nozzle_temperature_range_high': ['220'],
      'hot_plate_temp': ['55'], 'hot_plate_temp_initial_layer': ['55'], 'textured_plate_temp': ['55'], 'textured_plate_temp_initial_layer': ['55'],
      'version': '2.3.1.0'}
src = json.loads(open(UD + 'GeeeTech PLA Matte Stone Gray @MINIIS.json', 'rb').read().decode('utf-8-sig'))
om = dict(src)
nm2 = 'GeeeTech PLA Matte Grey @MINIIS'
om.update(name=nm2, default_filament_colour=[COLOUR], filament_notes=[NOTES], filament_settings_id=[nm2], filament_vendor=['GeeeTech'])
for d, base in ((oi, {}), (om, src)):
    for k in d:
        if k not in base and k not in ('from', 'name', 'inherits', 'version', 'is_custom_defined'):
            assert mm.find(b'\x00' + k.encode() + b'\x00') >= 0, 'unknown Orca key ' + k
out[UD + nm + '.json'] = dump(oi); out[UD + nm + '.info'] = info('GFSA04')
out[UD + nm2 + '.json'] = dump(om); out[UD + nm2 + '.info'] = info('OGFSL99_02')

# ================= report / write =================
for p, b in out.items():
    assert not os.path.exists(p), 'exists: ' + p
    print(('WRITE ' if WRITE else 'would write '), p.replace(H, ''), len(b), 'bytes')
d = {k: S[k] for k in INDX}; print('2.x INDX values:', d)
if WRITE:
    for p, b in out.items(): open(p, 'wb').write(b)
    print('written', len(out), 'files')
