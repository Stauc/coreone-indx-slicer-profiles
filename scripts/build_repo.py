import os, re, glob, json, shutil, sys
H = os.path.expanduser('~/mnt/')
R = H + 'Downloads/coreone-indx-slicer-profiles/'
assert not os.path.exists(R), 'repo folder already exists'
def put(src, dst_rel):
    dst = R + dst_rel; os.makedirs(os.path.dirname(dst), exist_ok=True); shutil.copy(src, dst); return dst
n = {}
# --- PrusaSlicer 2.x
for sub in ('filament', 'print', 'printer'):
    for f in sorted(glob.glob(H + f'Roaming--PrusaSlicer/{sub}/*INDX*.ini')):
        put(f, f'slicers/prusaslicer-2.x/{sub}/' + os.path.basename(f)); n[f'ps2x/{sub}'] = n.get(f'ps2x/{sub}', 0) + 1
# --- PrusaSlicer 3 alpha
for f in sorted(glob.glob(H + 'PrusaSlicer3-dev/presets/user/prusa-research-fff/PrusaResearch/*.yaml')):
    put(f, 'slicers/prusaslicer-3-alpha/presets/user/prusa-research-fff/PrusaResearch/' + os.path.basename(f)); n['ps3'] = n.get('ps3', 0) + 1
# --- OrcaSlicer (json only; .info files are regenerated by Orca)
O = H + 'Roaming--OrcaSlicer/user/default/'
for sub in ('filament', 'process', 'machine'):
    for f in sorted(glob.glob(O + f'{sub}/*INDX*.json')):
        b = os.path.basename(f)
        rel = f'slicers/orcaslicer/flowtest/{sub}/{b}' if 'FLOWTEST' in b else f'slicers/orcaslicer/{sub}/{b}'
        dst = put(f, rel); n[f'orca/{sub}'] = n.get(f'orca/{sub}', 0) + 1
        if sub == 'machine':      # scrub every host / credential field
            j = json.load(open(dst, encoding='utf-8'))
            for k in list(j):
                if re.search(r'^(print_host|print_host_webui|printhost_apikey|printhost_user|printhost_password|printhost_cafile|printhost_port)$', k):
                    j[k] = ''
            open(dst, 'wb').write((json.dumps(j, indent=4, sort_keys=True).replace('\n', '\r\n') + '\r\n').encode('utf-8'))
# --- PrusaSlicer 2.x printer presets: make sure host fields are empty (they were)
for f in glob.glob(R + 'slicers/prusaslicer-2.x/printer/*.ini'):
    t = open(f, 'rb').read().decode('utf-8')
    t = re.sub(r'(?m)^(print_host|printhost_apikey|printhost_cafile|printhost_password|printhost_user|printhost_port) = [^\r\n]*', r'\1 = ', t)
    open(f, 'wb').write(t.encode('utf-8'))
# --- scripts
for f in sorted(glob.glob(os.path.expanduser('~/scripts/*.py'))):
    put(f, 'scripts/' + os.path.basename(f)); n['scripts'] = n.get('scripts', 0) + 1
open(R + '.gitignore', 'w').write('__pycache__/\n*.pyc\n*.bak\n*.lock\n.DS_Store\nThumbs.db\n# never commit real printer hosts or keys\n*apikey*\n*.env\n')
print(n)
