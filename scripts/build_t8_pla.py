import sys, os, re, datetime
sys.path.insert(0, os.path.expanduser('~/scripts'))
from lib2x import parse_user, resolve, RP
WRITE = '--write' in sys.argv
HDR = datetime.datetime.utcnow().strftime('# generated by PrusaSlicer 2.9.7 on %Y-%m-%d at %H:%M:%S UTC')
NAME = 'Prusament PLA @COREONEINDX 1.0HF - T8'
OUT = RP + 'filament/' + NAME + '.ini'
COND = ('printer_notes=~/.*INDX_MIXED_NOZZLES.*/ and ((nozzle_diameter[0]==1 and nozzle_high_flow[0]) '
        'or (nozzle_diameter[7]==1 and nozzle_high_flow[7]))')
T, _ = parse_user(RP + 'filament/Prusament PLA @COREONEINDX HF0.4 - GECO.ini')          # full key set
P = resolve('filament', 'Prusament PLA @COREONEINDX HF0.4')
S = dict((k, P.get(k, v)) for k, v in T.items())
S.update(inherits='Prusament PLA @COREONEINDX HF0.4', compatible_printers='', compatible_printers_condition=COND, filament_settings_id='""')
# values Prusa uses for its largest official INDX PLA nozzle (0.8 HF), nearest to a 1.0
S.update(min_fan_speed='85', slowdown_below_layer_time='19', filament_minimal_purge_on_wipe_tower='18',
         filament_retract_restart_extra_toolchange='0.05')
S['start_filament_gcode'] = P['start_filament_gcode'].replace('M572 S0.038', 'M572 S0.013')
assert 'M572 S0.013' in S['start_filament_gcode']
S['filament_notes'] = ('"Prusament PLA for the 1.0 mm high-flow nozzle on T8 of the mixed-nozzle INDX printers. '
                       'Prusa has no 1.0 profile; temperatures and flow are the HF 0.4 values, fan, purge and pressure advance follow Prusa\'s 0.8 HF PLA."').replace("\\'", "'")
assert set(S) == set(T)
lines = [HDR] + [f'{k} = {S[k]}' for k in sorted(S)]
data = ('\r\n'.join(lines) + '\r\n').encode('utf-8')
print('diff vs vendor HF0.4 parent:', {k: (P[k][:22], S[k][:22]) for k in S if k in P and P[k] != S[k]})
# condition test under three ways PrusaSlicer might evaluate it
def ev(cond, nd, hf, notes):
    e = cond.replace('printer_notes=~/.*INDX_MIXED_NOZZLES.*/', 'NOTES')
    e = re.sub(r'nozzle_diameter\[(\d)\]', r'ND[\1]', e); e = re.sub(r'nozzle_high_flow\[(\d)\]', r'HF[\1]', e)
    return eval(e, {'ND': nd, 'HF': hf, 'NOTES': notes})
ND = [0.4]*6 + [0.25, 1.0]; HFv = [1,1,1,1,1,0,0,1]
for k in range(8):
    g = ev(COND, ND, HFv, True)
    sl = ev(COND, [ND[k]], [HFv[k]], True) if False else None
    sw_nd = ND[:]; sw_hf = HFv[:]; sw_nd[0], sw_nd[k] = sw_nd[k], sw_nd[0]; sw_hf[0], sw_hf[k] = sw_hf[k], sw_hf[0]
    try: sl = ev(COND, [ND[k]], [HFv[k]], True)
    except IndexError: sl = 'error(=compatible)'
    print(f'  T{k+1}: as-is={g}  slice-per-extruder={sl}  swap-per-extruder={ev(COND, sw_nd, sw_hf, True)}')
assert not os.path.exists(OUT)
if WRITE: open(OUT, 'wb').write(data); print('written', OUT.replace(RP, ''))
