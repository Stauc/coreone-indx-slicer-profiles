#!/usr/bin/env python3
"""GeeeTech PLA TriColor Silk Blue+Purple+Black. --write to apply."""
import sys, os, json, time, mmap, datetime, collections, uuid, base64, secrets
sys.path.insert(0, os.path.expanduser('~/scripts'))
from lib2x import parse_user, resolve, RP
WRITE = '--write' in sys.argv
H = os.path.expanduser('~/mnt/')
HDR = datetime.datetime.utcnow().strftime('# generated by PrusaSlicer 2.9.7 on %Y-%m-%d at %H:%M:%S UTC')
EPOCH = int(time.time())
NAME = 'GeeeTech PLA TriColor Silk Blue+Purple+Black'
COLOUR = '#5B3FA0'; COST = '14.49'; SPOOL = '193'; DENS = '1.24'
T_NOZ, T_FIRST, T_BED = '215', '220', '55'
NOTES = ('GeeeTech Silk PLA TriColor Blue+Purple+Black, 1.75 mm, 1 kg, co-extruded. Printing temperature 195-230 C (as given by the owner; Geeetech publishes none). '
         'Heated bed 50-60 C and density 1.24 from community data for Geeetech silk PLA. Dimensional accuracy +/-0.03 mm. Base: Prusa silk PLA settings.')
out = collections.OrderedDict()

def ini(od): return ('\r\n'.join([HDR] + [f'{k} = {od[k]}' for k in sorted(od)]) + '\r\n').encode('utf-8')
COMMON = dict(temperature=T_NOZ, first_layer_temperature=T_FIRST, bed_temperature=T_BED, first_layer_bed_temperature=T_BED,
              filament_cost=COST, filament_density=DENS, filament_spool_weight=SPOOL, filament_vendor='GeeeTech', filament_colour=COLOUR,
              filament_notes='"%s"' % NOTES, filament_settings_id='""')

# ---- PrusaSlicer 2.x INDX (full dump: GECO file = key template, Prusa silk = values)
T, _ = parse_user(RP + 'filament/Prusament PLA @COREONEINDX HF0.4 - GECO.ini')
P = resolve('filament', 'Generic PLA Silk @COREONEINDX HF0.4')
S = collections.OrderedDict((k, P.get(k, v)) for k, v in T.items())
S.update(inherits='Generic PLA Silk @COREONEINDX HF0.4', compatible_printers='', **COMMON)
assert set(S) == set(T)
out[RP + 'filament/%s @COREONEINDX HF0.4.ini' % NAME] = ini(S)
# ---- PrusaSlicer 2.x Mini IS (full dump: Stone Gray file = key template, Prusa silk @MINIIS = values)
M, _ = parse_user(RP + 'filament/GeeeTech PLA Matte Grey @MINIIS.ini')
PM = resolve('filament', 'Generic PLA Silk @MINIIS')
SM = collections.OrderedDict((k, PM.get(k, v)) for k, v in M.items())
SM.update(inherits='Generic PLA Silk @MINIIS', **COMMON)
for k in ('extrusion_multiplier', 'start_filament_gcode', 'filament_max_volumetric_speed'): SM[k] = PM[k]       # Prusa silk values, not the Stone Gray calibration
assert set(SM) == set(M)
out[RP + 'filament/%s @MINIIS.ini' % NAME] = ini(SM)

# ---- PrusaSlicer 3 alpha13 (INDX HF0.4): proven Prusament-PLA leaf + Prusa's silk values written out
def rid(): return base64.b64encode(secrets.token_bytes(16)).decode().rstrip('=')
ps3 = f'''kind: filament
id: {uuid.uuid4()}
variants:
- condition: ((printer.base_model == "COREONE_INDX") and (tool.nozzle_diameter == 0.4) and tool.nozzle_high_flow)
  id: {rid()}
  name: {NAME} @COREONEINDX HF0.4
  unconditional_inherits:
  - h2BZOYfPRV2UKu1BEaGnPw
  values:
    temperature: {T_NOZ}
    first_layer_temperature: {T_FIRST}
    filament_max_volumetric_speed: 12.5
    slowdown_below_layer_time: 12
    pressure_advance_value: 0.025
    filament_infill_max_crossing_speed: 120
    cooling_slowdown_logic: consistent_surface
    cooling_perimeter_transition_distance: 10
    filament_cost: {COST}
    filament_density: {DENS}
    filament_colour: '{COLOUR}'
    filament_vendor: GeeeTech
    filament_spool_weight: {SPOOL}
    filament_notes: '{NOTES}'
  features:
    based_id: h2BZOYfPRV2UKu1BEaGnPw
    based_root_id: Prusament PLA
'''
import yaml; yaml.safe_load(ps3)
out[H + 'PrusaSlicer3-dev/presets/user/prusa-research-fff/PrusaResearch/filament-%s @COREONEINDX HF0.4.yaml' % NAME] = ps3.encode('utf-8')

# ---- OrcaSlicer
UD = H + 'Roaming--OrcaSlicer/user/default/filament/'
def dump(d): return (json.dumps(d, indent=4, ensure_ascii=False, sort_keys=True).replace('\n', '\r\n') + '\r\n').encode('utf-8')
def info(): return ('sync_info = create\r\nuser_id = \r\nsetting_id = \r\nbase_id = \r\nupdated_time = %d\r\n' % EPOCH).encode()
dll = open(H + 'Program Files--OrcaSlicer/OrcaSlicer.dll', 'rb'); mm = mmap.mmap(dll.fileno(), 0, access=mmap.ACCESS_READ)
SYSM = 'Prusa CORE One INDX 8T HF 0.4 nozzle'
NEWM = ['Prusa CORE One INDX 8T Mixed Nozzles - LAN', 'Prusa CORE One INDX 8T Mixed Nozzles - Connect']
def orca(nm, inherits, compat, maxvol):
    d = {'compatible_printers': compat, 'default_filament_colour': [COLOUR], 'filament_cost': [COST], 'filament_density': [DENS],
         'filament_max_volumetric_speed': [maxvol], 'filament_notes': [NOTES], 'filament_settings_id': [nm], 'filament_vendor': ['GeeeTech'],
         'from': 'User', 'inherits': inherits, 'is_custom_defined': '0', 'name': nm,
         'nozzle_temperature': [T_NOZ], 'nozzle_temperature_initial_layer': [T_FIRST], 'nozzle_temperature_range_low': ['195'], 'nozzle_temperature_range_high': ['230'],
         'hot_plate_temp': [T_BED], 'hot_plate_temp_initial_layer': [T_BED], 'textured_plate_temp': [T_BED], 'textured_plate_temp_initial_layer': [T_BED],
         'version': '2.3.1.0'}
    for k in d:
        if k not in ('from', 'name', 'inherits', 'version', 'is_custom_defined'): assert mm.find(b'\x00' + k.encode() + b'\x00') >= 0, k
    return d
n1 = '%s @Prusa CORE One INDX' % NAME; n2 = '%s @MINIIS' % NAME
out[UD + n1 + '.json'] = dump(orca(n1, 'Generic PLA Silk @Prusa CORE One INDX', [SYSM, SYSM + ' - LAN', SYSM + ' - Connect'] + NEWM, '12.5')); out[UD + n1 + '.info'] = info()
out[UD + n2 + '.json'] = dump(orca(n2, 'Generic PLA Silk @System', ['Prusa MINIIS 0.4 nozzle'], '7'));                                               out[UD + n2 + '.info'] = info()

for p, b in out.items():
    assert not os.path.exists(p), 'exists: ' + p
    print(('WRITE ' if WRITE else 'would write '), p.replace(H, ''), len(b))
print('2.x INDX: ', {k: S[k] for k in ('temperature', 'first_layer_temperature', 'bed_temperature', 'filament_max_volumetric_speed', 'min_fan_speed', 'slowdown_below_layer_time')})
print('2.x MINIIS:', {k: SM[k] for k in ('temperature', 'first_layer_temperature', 'bed_temperature', 'filament_max_volumetric_speed', 'extrusion_multiplier')})
if WRITE:
    for p, b in out.items(): open(p, 'wb').write(b)
    print('written', len(out), 'files')
